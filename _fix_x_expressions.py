def main() -> None:
    total_replacements = 0
    files_touched: set[str] = set()

    for md_path in sorted(ROOT.glob("0?_*.md")) + sorted(ROOT.glob("1?_*.md")):
        text = md_path.read_text(encoding="utf-8")
        new_text = text
        local_count = 0
        for old, new in EDITS:
            if old in new_text:
                new_text = new_text.replace(old, new)
                local_count += 1
        if local_count > 0:
            md_path.write_text(new_text, encoding="utf-8")
            total_replacements += local_count
            files_touched.add(md_path.name)
            print(f"  ✓ {md_path.name}: {local_count}건")

    print(f"\n총 {total_replacements}건 치환, {len(files_touched)}개 파일 수정")


if __name__ == "__main__":
    main()
